package Rooms.Enums;

/**
 * Represents the possible statuses of a hotel room.
 */
public enum RoomStatus {

    /** Indicates that the room is available for booking. */
    AVAILABLE,

    /** Indicates that the room is currently occupied by a guest. */
    OCCUPIED,

    /** Indicates that the room is undergoing maintenance. */
    MAINTENANCE,

    /** Indicates that the room is being cleaned. */
    CLEANING
}